#!/usr/bin/env python3
"""
rm2c_port.py  -  Turns an RM2C export of a ROM Manager hack into scripts Ghostship loads from the hack's o2r.

RM2C exports a ROM Manager ROM to decomp C. Its level scripts and custom behaviors are the hack's code; its assets
come from the player's ROM (tools/romhacks/rom_manager.py writes their YAMLs with the same names). This writes the
scripts as text resources (docs/romhacks/SCRIPTS.md), which the extractor packs into the romhack's o2r:

    scripts/levels/<level>.xml      each level's script; replaces level_<level>_entry
    scripts/behaviors/<name>.xml    each custom behavior, found by name when a script uses it

Asset names become archive paths; behaviors, functions and constants stay names the runtime resolves. Anything the
runtime wouldn't know is reported.

    python3 tools/romhacks/rm2c_port.py --rm2c extracted/ --added-behaviors hack.patch \\
        --out tools/romhacks/<name>/scripts --custom-bhv <bhvName> --extra extra.yml

`extracted/` holds the files of the RM2C export.
"""

import argparse
import glob
import os
import re

HEADER = "// Generated by tools/romhacks/rm2c_port.py from the hack's RM2C export. Do not edit by hand."

IDENT = re.compile(r"\b[A-Za-z_][A-Za-z0-9_]*\b")
ARRAY = re.compile(r"const\s+LevelScript\s+(\w+)\s*\[\s*\]\s*=\s*\{(.*?)\};", re.S)
BEHAVIOR = re.compile(r"const\s+BehaviorScript\s+(\w+)\s*\[\s*\]\s*=\s*\{(.*?)\};", re.S)
ASSET_DECL = re.compile(r"char\s+(\w+)\s*\[\s*\]\s*=\s*\"__OTR__([^\"]+)\"")


def index_assets(include_dir):
    """Maps every asset declared under include/ to its archive path."""
    index = {}
    for path in sorted(glob.glob(os.path.join(include_dir, "**", "*.h"), recursive=True)):
        text = open(path, encoding="utf-8", errors="replace").read()
        for name, asset in ASSET_DECL.findall(text):
            index.setdefault(name, asset)
    return index


def runtime_names(root):
    """What the runtime resolves by name: commands, behaviors, functions, level scripts and constants."""
    gen = os.path.join(root, "src", "port", "scripts", "generated")
    names = {"level": set(), "behavior": set(), "symbol": set()}
    for kind, f in (("level", "LevelCommands.inc"), ("behavior", "BehaviorCommands.inc")):
        names[kind] = set(re.findall(r"SCRIPT_COMMAND\((\w+),", open(os.path.join(gen, f)).read()))
    names["symbol"] = set(re.findall(r"SCRIPT_\w+\((\w+)\)", open(os.path.join(gen, "ScriptSymbols.inc")).read()))
    names["symbol"] |= {"NULL", "TRUE", "FALSE"}
    return names


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def resolve_conditionals(text, defines=()):
    """Keeps the #ifdef/#ifndef/#else branches that apply when only `defines` are set."""
    out, stack = [], []
    for line in text.splitlines():
        s = line.strip()
        m = re.match(r"#\s*(ifdef|ifndef)\s+(\w+)", s)
        if m:
            stack.append((m.group(2) in defines) == (m.group(1) == "ifdef"))
        elif re.match(r"#\s*else", s):
            stack[-1] = not stack[-1]
        elif re.match(r"#\s*endif", s):
            stack.pop()
        elif all(stack):
            out.append(line)
    return "\n".join(out)


# Segment loads keep their ROM arguments only for the N64; Ghostship's macros ignore them.
SEGMENT_SYMBOL = re.compile(r"^_\w+SegmentRom(Start|End)$")


class Port:
    def __init__(self, args):
        self.args = args
        self.assets = index_assets(args.include)
        self.runtime = runtime_names(args.root)
        self.custom_bhvs = set()
        self.problems = {}
        # The export's decomp names some vanilla behaviors differently; match those by case.
        bhv_text = open(os.path.join(args.include, "behavior_data.h"), encoding="utf-8").read()
        self.bhv_by_lower = {n.lower(): n for n in re.findall(r"BehaviorScript\s+(\w+)\s*\[", bhv_text)}
        self.renames = dict(r.split("=", 1) for r in args.rename)
        # Assets the extra YAML extracts, by the level folder they extract into.
        self.extra_paths = {name: f"{args.asset_root}/{folder}/{name}"
                            for folder, names in args.extra.items() for name in names}

    def rename(self, ident):
        if ident in self.renames:
            return self.renames[ident]
        if ident.startswith("bhv") and not ident.startswith(self.args.custom_bhv) and ident not in self.runtime["symbol"]:
            return self.bhv_by_lower.get(ident.lower(), ident)
        return ident

    def resolve(self, ident, folder, locals_, commands, where):
        """An identifier in a command's arguments, as the script should write it."""
        ident = self.rename(ident)
        if SEGMENT_SYMBOL.match(ident):
            return "0"
        if ident in locals_ or ident in commands or ident in self.runtime["symbol"]:
            return ident
        if ident.startswith(self.args.custom_bhv):
            return ident
        if ident in self.extra_paths:
            return f'"{self.extra_paths[ident]}"'
        if re.match(r"^(Geo|col)_\w+_0x[0-9a-f]+$", ident):
            return f'"{self.args.asset_root}/{folder}/{ident}"'
        if ident in self.assets:
            return f'"{self.assets[ident]}"'
        self.problems.setdefault(ident, set()).add(where)
        return ident

    def convert(self, body, folder, locals_, commands, where):
        body = resolve_conditionals(strip_comments(body))
        return IDENT.sub(lambda m: self.resolve(m.group(0), folder, locals_, commands, where), body)

    def level_xml(self, folder, src):
        text = open(src, encoding="utf-8", errors="replace").read()
        arrays = ARRAY.findall(text)
        if not arrays:
            return None
        locals_ = {n for n, _ in arrays}
        out = [f"{HEADER}\n// {folder}\n"]
        for name, body in arrays:
            body = self.convert(body, folder, locals_, self.runtime["level"], folder)
            for bhv in re.findall(r"\b" + re.escape(self.args.custom_bhv) + r"\w+", body):
                self.custom_bhvs.add(bhv)
            out.append(f"const LevelScript {name}[] = {{\n{format_commands(body)}\n}};\n")
        return xml("LevelScript", f"level_{folder}_custom_entry", "\n".join(out))

    def behavior_xmls(self, added):
        text = read_added_behaviors(added)
        out = {}
        for name, body in BEHAVIOR.findall(text):
            if not name.startswith(self.args.custom_bhv):
                continue
            body = self.convert(body, None, {name}, self.runtime["behavior"], name)
            src = f"{HEADER}\nconst BehaviorScript {name}[] = {{\n{format_commands(body)}\n}};\n"
            out[name] = xml("BehaviorScript", name, src)
        return out


def format_commands(body):
    lines = [l.strip() for l in body.strip().splitlines() if l.strip()]
    return "\n".join("    " + l for l in lines)


def xml(root, entry, source):
    assert "]]>" not in source
    return f'<{root} Version="0" Entry="{entry}"><![CDATA[\n{source}]]></{root}>\n'


def read_added_behaviors(path):
    """The export's behavior_data.c additions, from a file holding them or from the decomp patch itself."""
    text = open(path, encoding="utf-8", errors="replace").read()
    if not path.endswith((".patch", ".diff")):
        return text
    start = text.index("diff --git a/data/behavior_data.c")
    end = text.find("\ndiff --git", start + 1)
    diff = text[start : end if end >= 0 else len(text)]
    return "\n".join(l[1:] for l in diff.splitlines() if l.startswith("+") and not l.startswith("+++"))


def load_extra(path):
    extra = {}
    folder = None
    if not path:
        return extra
    for raw in open(path, encoding="utf-8"):
        line = raw.split("#", 1)[0].rstrip()
        if not line.strip():
            continue
        if not line.startswith(" "):
            folder = line.rstrip(":").strip()
            extra.setdefault(folder, set())
        else:
            m = re.search(r"name:\s*(\w+)", line)
            if m:
                extra[folder].add(m.group(1))
    return extra


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--rm2c", required=True, help="folder with the RM2C export's files")
    parser.add_argument("--added-behaviors", required=True,
                        help="the decomp patch, or a file with what the export added to data/behavior_data.c")
    parser.add_argument("--out", required=True, help="the hack's files folder, e.g. tools/romhacks/<name>/scripts")
    parser.add_argument("--custom-bhv", required=True, help="name prefix of the hack's own behaviors")
    parser.add_argument("--extra", help="extra assets YAML given to rom_manager.py yamls")
    parser.add_argument("--asset-root", default="levels", help="o2r folder the level YAMLs extract to")
    parser.add_argument("--rename", action="append", default=[], metavar="OLD=NEW",
                        help="rename an identifier the export uses, e.g. a behavior the decomp renamed")
    parser.add_argument("--root", default=".", help="the Ghostship checkout")
    args = parser.parse_args()
    args.include = os.path.join(args.root, "include")
    args.extra = load_extra(args.extra)

    port = Port(args)
    scripts = os.path.join(args.out, "scripts")
    levels = 0
    for src in sorted(glob.glob(os.path.join(args.rm2c, "levels", "*", "custom.script.c"))):
        folder = os.path.basename(os.path.dirname(src))
        text = port.level_xml(folder, src)
        if text:
            write(os.path.join(scripts, "levels", f"{folder}.xml"), text)
            levels += 1
    behaviors = port.behavior_xmls(args.added_behaviors)
    for name, text in behaviors.items():
        write(os.path.join(scripts, "behaviors", f"{name}.xml"), text)

    print(f"{levels} level scripts, {len(behaviors)} behaviors")
    for bhv in sorted(port.custom_bhvs - set(behaviors)):
        print(f"  ! {bhv} is used but the export doesn't define it")
    for ident, where in sorted(port.problems.items()):
        print(f"  ! {ident} isn't an asset, a runtime symbol or a constant (in {', '.join(sorted(where))})")


if __name__ == "__main__":
    main()
