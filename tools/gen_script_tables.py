#!/usr/bin/env python3
"""
gen_script_tables.py  -  Writes the tables Ghostship needs to load level and behavior scripts from archives.

Scripts in an o2r name their commands, the behaviors and functions they call and the constants they use.
The runtime turns them back into the arrays the decomp's macros produce, so this lists, from the headers:

    src/port/scripts/generated/LevelCommands.inc     every level script command macro (include/level_commands.h)
    src/port/scripts/generated/BehaviorCommands.inc  every behavior command macro (include/behavior_macros.h)
    src/port/scripts/generated/ScriptSymbols.inc     behaviors, native functions, level functions and scripts,
                                                     and the integer constants scripts use

Only names are written: the compiler works out every value. Run it again after adding a behavior, command or
constant:

    python3 tools/gen_script_tables.py
"""

import glob
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "port", "scripts", "generated")
HEADER = "// Generated by tools/gen_script_tables.py. Do not edit by hand.\n"

# Headers whose object-like #defines and enums become constants scripts can use.
CONSTANT_HEADERS = [
    "include/model_ids.h",
    "include/object_constants.h",
    "include/object_fields.h",
    "include/seq_ids.h",
    "include/dialog_ids.h",
    "include/surface_terrains.h",
    "include/level_commands.h",
    "include/geo_commands.h",
    "src/game/interaction.h",
    "src/game/object_list_processor.h",
    "src/game/shadow.h",
]

# Defines in those headers that aren't integer constants.
SKIP_CONSTANTS = re.compile(r"^(LEVEL_COMMANDS_H|GEO_COMMANDS_H|.*_H_?|OBJECT_FIELDS_INDEX_DIRECTLY|"
                            r"OBJECT_FIELD_\w+|CMD_\w+|BC_\w+)$")


def read(path):
    text = open(os.path.join(ROOT, path), encoding="utf-8", errors="replace").read().replace("\r\n", "\n")
    return text


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def command_macros(path, marker):
    text = strip_comments(read(path)).replace("\\\n", " ")
    macros = {}
    for m in re.finditer(r"^#define\s+([A-Z_0-9]+)\(([^)]*)\)(.*)$", text, re.M):
        name, args, body = m.groups()
        # CMD_* and BC_* are the encoding helpers, except the behavior NOP commands.
        if name.startswith("BC_") or (name.startswith("CMD_") and not name.startswith("CMD_NOP_")):
            continue
        macros[name] = ([a.strip() for a in args.split(",") if a.strip()], body)
    commands = {n for n, (_, body) in macros.items() if marker in body}
    # Shorthands like OBJECT expand to another command.
    changed = True
    while changed:
        changed = False
        for name, (_, body) in macros.items():
            if name not in commands and any(re.search(r"\b" + c + r"\s*\(", body) for c in commands):
                commands.add(name)
                changed = True
    return [(n, macros[n][0]) for n in macros if n in commands]


def write_commands(path, macros):
    lines = [HEADER, "// SCRIPT_COMMAND(name, argument count, (arguments))\n"]
    for name, args in macros:
        call = ", ".join(f"V({i})" for i in range(len(args)))
        lines.append(f"SCRIPT_COMMAND({name}, {len(args)}, ({call}))\n")
    write(path, "".join(lines))


def constants():
    names = []
    for path in CONSTANT_HEADERS:
        text = strip_comments(read(path)).replace("\\\n", " ")
        # Object-like #defines; function-like ones are followed directly by '('.
        for m in re.finditer(r"^#\s*define\s+([A-Za-z_][A-Za-z0-9_]*)(?!\()[ \t]+(\S.*)$", text, re.M):
            name, body = m.groups()
            if SKIP_CONSTANTS.match(name) or '"' in body or "{" in body:
                continue
            if path.endswith("object_fields.h") and not name.startswith("o"):
                continue
            names.append(name)
        for body in re.findall(r"\benum\b[^{;]*\{(.*?)\}", text, re.S):
            for item in body.split(","):
                m = re.match(r"\s*([A-Za-z_][A-Za-z0-9_]*)", item)
                if m:
                    names.append(m.group(1))
    # Level and course numbers come from the X-macro lists.
    for m in re.finditer(r"DEFINE_LEVEL\([^,]*,\s*(LEVEL_\w+)", read("levels/level_defines.h")):
        names.append(m.group(1))
    for m in re.finditer(r"DEFINE_(?:COURSE|BONUS_COURSE)\(\s*(COURSE_\w+)", read("levels/course_defines.h")):
        names.append(m.group(1))
    names += ["COURSE_NONE", "COURSE_MIN", "COURSE_MAX", "COURSE_STAGES_MAX", "COURSE_COUNT", "LEVEL_NONE",
              "LEVEL_COUNT", "LEVEL_MIN", "LEVEL_MAX"]
    return sorted(set(names))


def pointers():
    # behavior_data.h still declares a few behaviors nothing defines.
    defined = set(re.findall(r"BehaviorScript\s+(\w+)\s*\[\s*\]\s*=", read("data/behavior_data.c")))
    behaviors = [b for b in re.findall(r"BehaviorScript\s+(\w+)\s*\[", read("include/behavior_data.h")) if b in defined]
    natives = re.findall(r"CALL_NATIVE\(\s*(\w+)\s*\)", strip_comments(read("data/behavior_data.c")))
    level_funcs, level_scripts = [], []
    for path in sorted(glob.glob(os.path.join(ROOT, "levels", "**", "*.c"), recursive=True)):
        text = strip_comments(open(path, encoding="utf-8", errors="replace").read())
        level_funcs += re.findall(r"\bCALL(?:_LOOP)?\(\s*/\*arg\*/\s*-?\w+\s*,\s*/\*func\*/\s*(\w+)\s*\)", text)
        level_funcs += re.findall(r"\bCALL(?:_LOOP)?\(\s*-?\w+\s*,\s*(\w+)\s*\)", text)
    level_scripts += re.findall(r"LevelScript\s+(\w+)\s*\[\s*\]\s*;", read("levels/scripts.h"))
    return sorted(set(behaviors)), sorted(set(natives)), sorted(set(level_funcs)), sorted(set(level_scripts))


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def main():
    level = command_macros("include/level_commands.h", "CMD_")
    behavior = command_macros("include/behavior_macros.h", "BC_")
    write_commands(os.path.join(OUT, "LevelCommands.inc"), level)
    write_commands(os.path.join(OUT, "BehaviorCommands.inc"), behavior)

    behaviors, natives, level_funcs, level_scripts = pointers()
    consts = constants()
    lines = [HEADER]
    lines.append("// SCRIPT_BEHAVIOR(name): a behavior script\n")
    lines += [f"SCRIPT_BEHAVIOR({n})\n" for n in behaviors]
    lines.append("\n// SCRIPT_FUNCTION(name): a function behaviors or level scripts call\n")
    lines += [f"SCRIPT_FUNCTION({n})\n" for n in sorted(set(natives) | set(level_funcs))]
    lines.append("\n// SCRIPT_LEVEL_SCRIPT(name): a level script other scripts jump to\n")
    lines += [f"SCRIPT_LEVEL_SCRIPT({n})\n" for n in level_scripts]
    lines.append("\n// SCRIPT_CONSTANT(name): an integer constant\n")
    lines += [f"SCRIPT_CONSTANT({n})\n" for n in consts]
    write(os.path.join(OUT, "ScriptSymbols.inc"), "".join(lines))
    print(f"{len(level)} level commands, {len(behavior)} behavior commands, {len(behaviors)} behaviors, "
          f"{len(set(natives) | set(level_funcs))} functions, {len(level_scripts)} level scripts, "
          f"{len(consts)} constants")


if __name__ == "__main__":
    main()
